/*
 * ---- 追加（`fs.append`）：重跑凭什么能说"我没做" ----
 *
 * 这是本目录里**第一个"重复调用会真的多写一份"**的能力，也是第一个不靠框架
 * 字段、只靠契约自证的能力。
 *
 * 为什么不是给 apply 加一个 `mode=append`：
 *   - 方言 `path\ncontent` 只有两段，塞 mode 就成三段 ⇒ 同一能力两套方言
 *     （与 `fs.diff` 拒绝 dry-run 开关是同一条理由）；
 *   - 更硬的一条：**两者的失败表不同**。apply 失败停在"旧内容完好"，append
 *     失败可能已经多写了半段 —— 放进一个 handler 就得让一个实现说两种谎。
 *
 * ---- 重跑为什么能自证：尾部就是"我上次写到哪"的凭据 ----
 *
 * 框架的重跑（`FULL` 后把 exec 从头再调一次）碰不到它：收据长度有上界
 * ⇒ 永不 `FULL`。真正会发生的是**模型把同一个调用发两次**（实测会）。
 * 那件事框架看不见（它只看到一个没失败的 WorkItem），只能由能力自己回答。
 *
 * 答法是**看尾部**：追加前读文件最后 blen 字节，与 payload 逐字节比，
 * 相同就报 `same` 且一个字节都不写。于是：
 *   - 重跑的第二次拿到 `same` ⇒ "这次我没做"有据可查；
 *   - 不需要调用方提供原长度（那是三段方言），也不需要它先查询；
 *   - 与"追加日志"这个形状本身一致：尾部就是上次写到的位置。
 *
 * ★ 边界（必须写清，否则会被当成承诺）：
 *   1. **挡不住并发写者。** 比完到写之间别人可能追加（TOCTOU）。`O_APPEND`
 *      只保证单次 write 的定位原子，不保证"比较 + 追加"是一步。要那一步
 *      得上 `flock` —— 另一个自由度，不在这一刀。
 *   2. **连续两次追加完全相同的内容会被判成 `same`。** 真想再来一条（日志里
 *      两条相同事件），用 `fs.write_apply` 整体重写，或让内容自带区分
 *      （时间戳 / 序号）。
 *   3. 只比尾部**恰好 blen 字节**，判据是位置不是"内容出现过"：文件尾部是
 *      `ABC` 而 payload 是 `BC` 时判相同（那确实是尾部）；payload 是 `AB` 时
 *      判不同（位置不对）。写成"只比内容是否出现过"会让同一段被跳过。
 *
 * ---- 文件不存在：报 `absent`，不创建 ----
 *
 * "不存在"不是错误，是应用层事实（与 `fs.diff` 的 `absent` 同一个口径）。
 * 不带 `O_CREAT` 的两个理由：
 *   1. 能创建的 append 会在"能建不能改"与"能改"两档都合法 ⇒ 一个能力横跨
 *      两档，档位就说不清它允许什么（每档只该说一件事）；
 *   2. 创建已经是 `fs.write_apply` 的 `absent` 那一格。两个能力在这里正好
 *      咬合：append 报 `absent`，模型转去 apply。
 *
 * 收据三档（`absent` 是事实不是失败，rc = `CXF_OK`）：
 *   wrote <b> @<total>   追加 b 字节，文件现在 total 字节
 *   same <total>         尾部已是这段内容，**未开写通道**
 *   absent               文件不存在，什么都没做
 *
 * ★ 与 apply 的断言差别（写测试时别抄错）：apply 走 tmp + rename ⇒ 写入必换
 *   inode，所以 `st_ino` 能区分"没动"与"写了相同内容"。append 是原地追加
 *   ⇒ inode **恒不变**，能区分的只有 `st_size`（与 `st_mtime`）。同一条不变式
 *   在两种实现里要用两个不同的观测量 —— 判据跟着实现形状走，最直接的一例。
 *
 * 三种错分开报：
 *   FORMAT  没有路径
 *   RANGE   路径形状不合契约 / 越界 / 目标不是普通文件（目录 / 符号链接）
 *   IO      父目录不存在 / 读写失败（**多写的字节已落盘，没有撤销**）
 */
#define FS_APPEND_OUT_MAX   48u          /* "wrote 4294967295 @18446744073709551615\n" = 39 */
#define FS_APPEND_OUT_HINT  64u          /* ≥ OUT_MAX：否则第一次就 FULL ⇒ 白跑一轮扩容 */

cxf_result fs_append_exec(const void *ctx, const char *args, uint32_t args_len,
                          char *out, uint32_t out_cap, uint32_t *out_len);

