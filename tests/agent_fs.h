/*
 * fs.grep —— 目录里第一个**真实**能力（§4.15.1 对比台的胜者转正）。
 *
 * 为什么是它：`bench_budget` 上同一份语料、同一条任务，"查询感知"的
 * grep 最坏预算 96 字节、噪声 0，而"零感知"的整文塞入最坏 8192 字节、噪声 7。
 * 但这张表是在一个**不链内核**的量尺上跑出来的，所以它证明的是"哪种策略好"，
 * 不是"框架能跑真实载荷"。要证明后者，必须有一个读真实文件系统、经由
 * tick × 四 phase 执行、结果按 blob 交接的实现。这个文件就是那一个。
 *
 * 它同时补掉 STATUS §1.1 的第 ④ 条缺口：在此之前目录里 5 个实现全是
 * `cap_mock_price`（把 args 哈希成价格），所以"回路通了"这句话里的
 * 每一段字节都是假的 —— 于是所有关于载荷的量（§4.15 的 b*、§4.12 的
 * 命中率、§7.3 的索引收益）都无物可测。
 *
 * ---- 三条设计决定，都是"能力 ABI 逼出来的"，不是偏好 ----
 *
 * 1. **根目录在 ctx 里，不在 args 里。**
 *    args 是 payload，payload 可以来自模型。若 handler 接受 payload 里的
 *    路径，一个幻觉出来的 `../../../etc/passwd` 就是一次越权读取，而运行时
 *    无法判定 —— 它只看见"一串字节"。把 root 放进 `CapImpl.ctx` 之后，
 *    "这个实现能看哪片盘"变成**注册期事实**，与 §4.10 定的 ctx 纪律同构：
 *    谁知道背后的东西，谁负责。payload 因此只剩下 pattern 一个自由度。
 *
 * 2. **命中行数有硬上限，超了在输出里写 `#truncated <shown>/<total>`。**
 *    这是"有界可以，静默不行"（§3 第 15 条）在**输出侧**的样子。
 *    它不能走 `CXF_ERR_FULL`：FULL 的语义是"装不下，再给一倍容量"，
 *    执行层会翻倍重跑 5 次 —— 而截断是**语义上的输出就这么多**，
 *    扩容只会让同一批行重写一遍。两种"没写全"必须分开报，
 *    否则 `AGENT_RESULT_TRIES` 会被白白烧掉。
 *
 * 3. **遍历顺序由 `alphasort` 定死。**
 *    `readdir` 的顺序由文件系统给，同一次运行内都可能不同。若照抄，
 *    输出字节不可复现 ⇒ 请求体确定性（§4.10）那条硬契约在这条路径上失效，
 *    而且"重跑幂等"没法验证。排序的代价是每目录一次 qsort，
 *    换来的是**同一个目录树永远给出同一串字节**。
 */

/* 能力名与接口名。接口必须是 INT（有人产出的内部类型）——
 * 复用 task.text 是不行的：那是 EXT，EXT 不允许被产出。 */
#define CAPNAME_FS      "fs.grep"
#define IFACENAME_HITS  "fs.hits"

/* 一个能力最多写多少命中行。这不是性能参数，是**注意力参数**：
 * 命中 500 行塞进 8K 上下文，等于把 §4.15 的 context rot 请回来。
 * 真需要更多就让调用方分几次问（这本来就是 agent 该做的事）。 */
#define FS_GREP_MAX_HITS   32u

/* 递归深度上限。作用不是省时间，是**防目录环**：符号链接成环时
 * 深度是唯一的终止判据（`lstat` 跳过链接是第一道，这里是第二道）。 */
#define FS_GREP_MAX_DEPTH  4u

/* 单行读缓冲。超过它的行会被当成"部分行 + 余料"处理，
 * 余料吞到下一个换行且**不增加行号** —— 否则一份 minified 文件
 * 会让后面所有行号整体漂移，而路径+行号是索引项的锚点（§7.3）。 */
#define FS_GREP_LINE_MAX   512u
#define FS_GREP_PATH_MAX   512u

/* 起始容量提示。32 行 ×（路径 ~40 + 行号 ~6 + 内容 ~24）≈ 2.3 KiB，
 * 给 4 KiB 留出长行余量。写不足时仍会走 FULL → 翻倍重跑，
 * 而这条实现是幂等的（见下），所以重跑不改变语义。 */
#define FS_GREP_OUT_HINT   4096u

/* 装配期参数。root 是部署边界：一个进程一片根，要两片就构造两份描述符。 */
typedef struct FsCfg {
    const char *root;
    uint32_t    max_hits;    /* 0 = FS_GREP_MAX_HITS */
    uint32_t    max_depth;   /* 0 = FS_GREP_MAX_DEPTH */
    const AgentPolicy *policy;
} FsCfg;

/*
 * handler 本体。args = pattern（子串匹配，按字节比较，不做正则/大小写折叠）。
 *
 * 它是**纯函数**：同一份文件树 + 同一 pattern ⇒ 同一串字节。
 * 这条性质是它能安全重跑的全部理由 —— 与 mock 那个"返回 FULL 之前就推进剧本"
 * 的缺陷正好相反（§4.10 附录）。真实能力的幂等应该是常态，
 * 需要"重跑代价"的是 LLM 那一类，不是这一层。
 *
 * 三种错分开报（§3 第 20 条）：
 *   FORMAT  空 pattern —— 会命中一切，几乎必然是幻觉，直接拒
 *   IO      root 不存在或不是目录 —— 响亮失败，不返回空结果
 *           （空结果会被上层读成"库里没有这件事"，那是假否定）
 *   FULL    装不下，重跑有意义
 */
cxf_result fs_grep_exec(const void *ctx, const char *args, uint32_t args_len,
                        char *out, uint32_t out_cap, uint32_t *out_len);

/* 契约（进 bundle）与实现模板（ctx 由部署填，不进 bundle —— 理由见 .c 末尾）。 */
extern const IfaceDef fs_iface_hits;
extern const CapDef   fs_capdef_grep;
extern const CapImpl  fs_capimpl_grep;

/*
 * ===================================================================
 * fs.write_new —— 目录里第一个**会改变外部状态**的能力
 * ===================================================================
 *
 * `fs.grep` 证明的是"框架能跑真载荷"，但它**只读**：整个目录里没有一个能力
 * 能让 agent 完成一件会改变外部世界的事。于是"agent 具备基本能力了吗"这个问题
 * 一直答不了 —— 判据不是"能调工具"，是"能完成一件失败会留下痕迹的任务"。
 * 这一刀补的就是它（docs/agent.md §4.18.6）。
 *
 * ---- 为什么是 write_new，而不是 write / append ----
 *
 * 写系列里只有它同时满足两件在安全上最贵的事：
 *
 *   天然可逆  `O_CREAT|O_EXCL` ⇒ 逆操作是 `unlink`，且"这路径是我建的"
 *             由 `O_EXCL` 自己保证（不是由调用方记住）。§2.6 的判据是
 *             "可逆 ⇔ 逆操作所需的信息在正操作完成后仍然存在" —— 这里是
 *             文件系统自己保存的，不靠上下文。
 *   天然幂等  第二次同参数调用得到 `EEXIST`，且**不覆盖**。于是"重跑一次
 *             会怎样"第一次有一个不需要判断的答案。
 *
 * `write`（覆盖）两条都不满足：旧内容一破坏，逆操作所需的信息就没了。
 * 所以它排在第二刀，且必须带 dry-run —— 但那不在这份代码里（L5）。
 *
 * ---- 三条边界，各自对应一层 ----
 *
 *   L2 参数准入  目标按D-DATA检查规范组件和敏感名称，并沿根目录fd打开。
 *                拒绝 `.`／`..` 和符号链接组件，打开后再验证普通文件／链接数／保护inode；
 *                而绕过它的后果是"部署声明的边界"变成一句注释。
 *   L0 表达能力  payload 只有两个自由度（path / content）。建目录、改权限、
 *                删除都不在参数里 —— 想做得更多就加能力，不是加参数。
 *   写原子性     路径存在 ⟺ 内容完整。写失败就把刚建的文件 unlink 掉：
 *                "允许重跑"不是安全性，"失败不留痕迹"才是。
 *
 * ---- 契约与实现都不进 bundle ----
 *
 * 与 `cap/agent.step` 同一处理：`fs.wrote` 是一个**新接口类型**，而不变式 7
 * 要求 INT 必须有人产出 ⇒ 类型、契约、实现必须在**同一次 sync** 之前到齐。
 * 更硬的理由是链头不变式（4）：`cap/fs.write_new` 一旦进了 bundle，所有
 * 用到 fs bundle 的部署都被迫交出一个写实现 —— **只读部署不该被迫声明写根**。
 * 所以这一组由部署方按需注册（见 .c 末尾那段）。
 */

/* 接口类型。能力名在 `agent_caps.h`（契约命名空间，运行时按名字查目录）；
 * 接口类型名留在这里，因为它只被这一个能力产出与消费。 */
#define IFACENAME_WROTE  "fs.wrote"

/* 路径上限。与 FS_GREP_PATH_MAX 分开写：读的上限由遍历决定，写的上限由
 * "路径组件检查与目录fd打开共同限定边界"决定，两者将来松绑的原因不同。 */
#define FS_WRITE_PATH_MAX  512u

/* 收据长度有**确定上界**：`new ` / `exists ` + 最多 20 位十进制 + 换行。
 * 于是在动文件系统之前就能判"装得下吗" —— 见 .c 里"先判容量，再动世界"。
 * 它不是 FS_GREP_OUT_HINT 那类"猜内容多大"的数：这个实现的输出长度有上界，
 * 所以它永不 `FULL`、永不触发扩容重跑 —— 这正是"写能力不会被重跑"的落点。 */
#define FS_WRITE_OUT_MAX   32u
#define FS_WRITE_OUT_HINT  64u

/*
 * 装配期参数：**一片根**。`fs.diff` / `fs.write_new` / `fs.write_apply` 共用
 * 同一个 ctx 类型，而且**必须指向同一个根** —— 否则"你看到的差异"和"你覆盖的文件"
 * 不是同一个文件，而这种错在代码里完全看不出来（两个能力各自都很对）。
 *
 * 与 `FsCfg` 分开仍然是必要的：那个还带着 max_hits / max_depth（遍历参数），
 * 而这里只有"边界在哪"。一个部署可以允许读整棵树、只允许写其中一片。
 */
typedef struct FsRootCfg {
    const char *root;   /* deployment-controlled root */
    const AgentPolicy *policy;
} FsRootCfg;

/*
 * handler。args = `path\ncontent`：
 *   第一个 '\n' 之前是**相对路径**，之后（含全部剩余字节）是**内容**，原样写盘。
 *   必须含 '\n' 分隔符；没有分隔符报 FORMAT，不把漏参数当作空内容。
 *   显式 `path\n` 仍表示空文件。write_apply / append 遵守同一约束。
 *
 * ★ **假设：只有两段。** 第一个 '\n' 之后**全部**是内容 ⇒ 这个格式承载不了
 *   第三个字段。写下来不是因为谨慎，是因为它**立刻就要被撞上**：下一刀
 *   `fs.write` 需要一个"只出 diff / 真落盘"的开关，而开关无处可放 ——
 *   塞进去要么变成三段式（于是同一个能力有两套 payload 方言），要么加一个
 *   假字段。结论只能是**加一个能力**（`fs.write` / `fs.write_apply`），
 *   与上面那句"想做得更多就加能力，不是加参数"一致。
 *   ⇒ 判据：任何格式都要写下"它能承载几段"，否则下一个需求会以**悄悄改方言**的
 *     形式落地，而方言的第二份实现在半年后才被发现不同步。
 *
 * 三种错分开报（§3 第 20 条）：
 *   FORMAT  没有路径（args 为空）—— 重试没用
 *   RANGE   路径形状不合契约（绝对路径 / 以 '/' 结尾 / 含 NUL / 越界 /
 *           目标已存在但不是普通文件）—— 设计边界
 *   IO      父目录不存在 / 权限不足 / 写失败 —— 环境事实
 *
 * 不进 FULL：输出长度有确定上界（见 FS_WRITE_OUT_HINT）。
 */
cxf_result fs_write_new_exec(const void *ctx, const char *args, uint32_t args_len,
                             char *out, uint32_t out_cap, uint32_t *out_len);

/* 契约 + 实现模板 + 接口。**都没有 CXF_SERVICE 注解** ⇒ 不进 bundle，
 * 由部署方与实现一起注册（理由见上面那段）。 */
extern const IfaceDef fs_iface_wrote;
extern const CapDef   fs_capdef_write_new;
extern const CapImpl  fs_capimpl_write_new;

/*
 * ===================================================================
 * fs.diff —— "如果我把这个文件换成这些字节，会发生什么"（零副作用）
 * ===================================================================
 *
 * **dry-run 不是写能力的一个开关，是另一个能力。** 理由两层，第二层是硬的：
 *
 * 1. `path\ncontent` 这个方言承载不下第三个字段（见上），塞进去就是同一能力
 *    两套方言 —— 而方言的第二份实现半年后才被发现不同步。
 * 2. 做成开关的话，部署侧就只剩**一个**事实："这个进程能不能写"。
 *    拆开之后有两个："能不能看差异"和"能不能覆盖"。只读部署挂 `fs.diff`
 *    不挂 `fs.write_apply` —— 于是"看"这件事不需要写权限。
 *
 * 组合由调用方拼：「先 diff 看，再 apply 写」。两段、两次调用 ——
 * 这不是绕远路，这正是"语义在组合里"的意思（§4.18.5）。
 *
 * ---- 输出（三种结局 + 三种标记）----
 *
 *   same                             内容逐字节相同：应用后什么都不会变
 *   absent <n> <lines>               路径不存在：应用会新建 n 字节 / lines 行
 *   diff <oldb> <newb> +<nl> -<ol>   行级差异，其后跟块
 *   @@ -<o> +<n> @@                  块起点（1-based）
 *    <ctx> / -<old> / +<new>         上下文 / 删除 / 新增
 *
 *   #eol                             行内容相同、字节不同（末尾换行 / 空行）
 *   #coarse bytes <sz>/<limit>       旧文件超过读入上限 ⇒ 旧侧行数未知（头里写 `-?`）
 *   #coarse lines <olded> <newed>/<limit>  行数超上限 ⇒ 只报计数，不做逐行
 *                                    （头里的计数仍是**两个文件的事实**，不截到上限）
 *   #omitted <k>                     块数超上限，后面的不列
 *
 * 没有 `#truncated`：输出容量不够走的是 **FULL**（语义"再给一倍"），
 * 与 `fs.grep` 的 `#truncated` 不是同一件事 —— 那个界是**语义上的输出就这么多**，
 * 扩容没用；这里的界是分配给你的那点地方不够，扩容有用。
 *
 * ---- 两个上限，都是**注意力参数**不是性能参数 ----
 * 把 2000 行上下文塞给模型，等于把 §4.15 的 context rot 请回来。所以
 * 「能比多少」和「能说多少」都要有界，且界要写进输出（`#coarse`）而不是静默。
 *
 * ★ 两个界在输出里的形状不同，因为**已知量不同**：
 *   旧文件超字节上限 ⇒ 根本没读，旧侧行数不可知 ⇒ 写 `-?`（不是 `-0`：
 *      "旧文件是空的"与"旧文件太大"是相反的判断，用 0 冒充会直接误导决策）；
 *   行数超上限 ⇒ 两侧都已切成行，计数准确 ⇒ 照实写。
 *   ⇒ 判据：任何"未知"都要写成未知，"0"永远只表示零。
 *
 * ★ 与 `fs.write_new` 的一个不对称，值得记：**它可能返回 FULL**。
 *   写能力不会（收据长度有上界），判据是"它是否把外部数据搬进 out"。
 *   所以"这个能力会不会被重跑"可以静态回答 —— diff 会，write_new 不会。
 */
#define IFACENAME_DIFFED    "fs.diffed"

#define FS_DIFF_MAX_BYTES   65536u   /* 旧文件读入上限：超了 #coarse bytes */
#define FS_DIFF_MAX_LINES   256u     /* 单侧行数上限：超了 #coarse lines */
#define FS_DIFF_CTX         2u       /* 每块上下文行 */
#define FS_DIFF_HUNK_MAX    8u       /* 最多列几块 */
#define FS_DIFF_OUT_HINT    2048u

/* LCS 表的大小**不是**一个独立参数：表按后缀分配，大小 = 旧行数 × 新行数，
 * 所以它的上限就是 MAX_LINES 的平方。写成两个可分别调的数会造出一对能互相
 * 矛盾的界（行数在界内、表却装不下），而那种矛盾的表现是一条莫名其妙的
 * `#coarse`。写成恒等式之后，"能比多少行"只有一个答案。 */
#define FS_DIFF_MAX_CELLS   (FS_DIFF_MAX_LINES * FS_DIFF_MAX_LINES)

/*
 * handler。args 与 `fs.write_new` **同一个方言**（`path\ncontent`）——
 * 同一族能力用同一套 payload 是合理的；"两套方言"指的从来是**一个能力**两套。
 *
 * 三种错分开报：
 *   FORMAT  没有路径
 *   RANGE   路径形状不合契约 / 越界 / 目标是目录或符号链接
 *   IO      父目录不存在 / 读失败
 *   FULL    输出装不下（**语义是"再给一倍"，与本实现无关的那种界**）
 */
cxf_result fs_diff_exec(const void *ctx, const char *args, uint32_t args_len,
                        char *out, uint32_t out_cap, uint32_t *out_len);

extern const IfaceDef fs_iface_diffed;
extern const CapDef   fs_capdef_diff;
extern const CapImpl  fs_capimpl_diff;

/*
 * ===================================================================
 * fs.write_apply —— 目录里第一个**不可逆**的能力
 * ===================================================================
 *
 * `write_new` 只会在"路径不存在"时动世界，所以它失败即无痕、重跑即无事。
 * `write_apply` 是"使这个文件**恰好等于**这些字节"——它会把旧内容毁掉，
 * 而逆操作所需的旧内容一旦没了就再也拿不回来（§2.6）。这是本目录第一次
 * 有一个"做错了没有退路"的能力，所以它的设计判据全部围绕一件事：
 *
 *   **要么看到全前的世界，要么看到全后的世界，没有第三种。**
 *
 * ---- 为什么是"一个动词覆盖三种结局"，而不是"必须已存在" ----
 *
 * `fs.diff` 已经给出三种结局，而它们各自对应**唯一**一个动作：
 *
 *   same     什么都别做（`write_apply` 自己也会判，见下"内容幂等"）
 *   absent   创建
 *   diff     覆盖
 *
 * 若把它拆成"只覆盖已存在的文件"，absent 那一格就得走 `write_new` ——
 * 于是"我看到的差异"与"我要落盘的动作"变成两个能力的两次调用，而中间
 * 那段时间里世界可以变（§4.18.7 已声明组合风险归 L5）。一个动词三种结局的
 * 好处不是省一个能力，是**让"该做什么"只剩下一个答案**：把内容交出去。
 *
 * ---- 内容幂等：`same` 是能力，不是优化 ----
 *
 * 它先比内容再决定写不写。这一格的收益有两处，都不是性能：
 *
 *   1. **重复调用可以答出来。** 模型把同一个调用发两次（实测会），第二次
 *      得到 `same <n>` —— 于是"我改过了"这个说法有据可查，而 `wrote` 的
 *      反复出现也不会被误读成"改了两次"。
 *   2. **不写就是真的没动。** inode 与 mtime 都不变，因为没打开写通道。
 *      这与"写了同样的内容"在文件系统层面是**可区分**的（见测试里那条
 *      inode 断言），而可区分才叫没动。
 *
 * ★ 它**不会** `FULL`：收据长度有上界，与 `write_new` 同一条（先判容量，
 *   再动世界）⇒ 框架的扩容重跑碰不到它。所以：
 *
 * ⇒ **它不是 A1（`CapRerun`）的读者。** 危险的不是框架重跑，是模型的重复
 *   调用，而那个由上面的内容幂等回答。
 *
 * ★ 但别顺手把 `fs.append` / `fs.move` 写成 `CapRerun` 的读者（v1.14.2 犯过）：
 *   `CapRerun` 挡的是**框架自己发起的重跑**，而框架只在 `FULL` 后重跑
 *   （`agent.c:1830`，`AGENT_RESULT_TRIES` 那个循环，且是**从头再调一次** `exec`）。
 *   fs 族的收据全是定长小串，实现又先判容量再动世界 ⇒ 永不 `FULL`
 *   ⇒ 这个字段对 fs 族一个字都不生效。
 *   **v1.14.5/v1.14.6 更正两处**（这里原先是错的说法，留着当反例）：
 *   ① 原写"第一个真读者必须在'输出不可预测 + 有副作用'的交集里，那是 `http.post`"
 *      —— 不成立：`http.post` 落码时主动拒绝 `FULL`（改报 `#truncated` / `RANGE`），
 *      于是 `CapRerun` **至今零读者**，且 grep 证实它零行代码 ⇒ 不建。
 *   ② 原写"`fs.append` 用乐观前置条件（调用方报出当前长度，不符就 `stale <actual>`）"
 *      —— v1.14.4 已否掉：三段方言 + 首次调用不知道该填什么，哨兵路径没有保护。
 *      实际实现是**尾部比较**（见上文）。
 *   fs 族要挡的是模型的重复调用，只能由能力自己的契约挡；`fs.move` 连契约都不需要：
 *   重跑时世界不变（源已不在 = 已经搬完），要修的只是收据分档，
 *   别把"报不清"与"多做了"写成同一类风险。
 *
 * ---- 覆盖必须原子（`O_TRUNC` 是错的） ----
 *
 * 直觉做法是 `open(O_WRONLY|O_CREAT|O_TRUNC)` 然后写。它错在一个地方：
 * `O_TRUNC` 在**写之前**就把旧内容毁了，此时若 `write` 失败（磁盘满 / 配额 /
 * NFS 断连），留下的是一个**半截新文件**，而旧内容已经不存在 —— 这正是
 * `write_new` 用 `unlink` 逃掉的那种失败，在这里**逃不掉**（unlink 只会
 * 让文件消失，不会把旧内容变回来）。
 *
 * 所以替换走"同目录临时文件 + rename"：`rename(2)` 在同一文件系统内是原子的，
 * 于是任何失败都停在**旧文件完好**那一侧。代价是每写一次多一次 rename，
 * 换来的是"路径存在 ⟺ 内容完整"这条不变式在**覆盖**场景下也成立。
 *
 * 两个附带决定：
 *   - 临时文件以 '.' 开头（`.cxf.XXXXXX`），于是 `fs.grep` 的"跳过点文件"
 *     这条规则顺带让中间态不会被打进检索结果；
 *   - **旧文件的权限位要保留**（`st_mode & 07777` 抄到临时文件上）。否则一次
 *     覆盖会把一个 0755 的脚本变成 0644，而"文件还能不能执行"不会出现在
 *     任何收据里 —— 这是一个完全静默的副作用。
 */
#define FS_APPLY_OUT_MAX   32u
#define FS_APPLY_OUT_HINT  64u

